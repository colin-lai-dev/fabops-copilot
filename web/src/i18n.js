// English display names for the six demo users (the data carries the Chinese ones).
const USER_EN = {
  op_fx1_etch: "FX1 etch operator",
  eng_fx1_etch: "FX1 etch engineer",
  eng_fx2_litho: "FX2 litho engineer",
  lead_fx1_multi: "FX1 process lead",
  mgr_fx2_all: "FX2 fab manager",
  admin_all: "System administrator",
};

export const LangContext = createContext("zh");

export function translate(lang, key, vars) {
  const s = STR[lang]?.[key] ?? STR.zh[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`)) : s;
}

export function useT() {
  const lang = useContext(LangContext);
  const t = (key, vars) => translate(lang, key, vars);
  t.lang = lang;
  t.user = (u) => (lang === "en" && u && USER_EN[u.user_id]) || u?.display_name || "";
  t.pick = (obj, field) => (lang === "en" && obj?.[`${field}_en`] != null ? obj[`${field}_en`] : obj?.[field]);
  return t;
}
